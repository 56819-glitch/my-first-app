import random
import time

def slow_print(text, delay=0.03):
    """ฟังก์ชันสำหรับพิมพ์ข้อความทีละตัวอักษรเพื่อเพิ่มความสมจริง"""
    for char in text:
        print(char, end='', flush=True)
        time.sleep(delay)
    print()

def game_over(reason):
    print("\n----------------------------------------")
    slow_print(f"💀 GAME OVER: {reason}")
    print("----------------------------------------")
    exit()

def victory():
    print("\n----------------------------------------")
    slow_print("🎉 VICTORY! คุณได้คีย์บอร์ด RGB ในตำนานมาครอบครอง!")
    slow_print("ตอนนี้คุณสามารถพิมพ์งานด้วยความเร็ว 999 WPM และไม่มีวันกดผิดอีกต่อไป!")
    print("----------------------------------------")
    exit()

def start_game():
    print("========================================")
    print(" 🕹️  THE QUEST FOR THE LEGENDARY KEYBOARD")
    print("========================================")
    slow_print("คุณคือ Dev มือใหม่ที่เพิ่งทำน้ำกาแฟหกใส่คีย์บอร์ดจนพัง...")
    slow_print("ทางเดียวที่จะแก้บั๊กงานให้เสร็จทันวันนี้ คือต้องไปเอา 'คีย์บอร์ด RGB ในตำนาน' ในห้องเก็บของออฟฟิศ!")
    print()

    # Choice 1
    slow_print("เดินไปตามทางเดิน... คุณเจอ 'หัวหน้าทีม' เดินตรงมาหาคุณ!")
    slow_print("1: แกล้งทำเป็นโทรศัพท์ แล้วเดินเนียนๆ ผ่านไป")
    slow_print("2: เดินเข้าไปทักทาย แล้วบอกว่า 'บั๊กเยอะจังเลยครับวันนี้!'")
    slow_print("3: ล้มตัวลงไปชักดิ้นชักกออยู่ที่พื้น")
    
    choice1 = input("\nเลือกทางเลือก (1-3): ")

    if choice1 == "1":
        slow_print("\nเนียนมาก! หัวหน้าไม่สนใจคุณ และเดินผ่านไป...")
    elif choice1 == "2":
        game_over("หัวหน้าลากคุณไปประชุมด่วน 4 ชั่วโมงเต็ม จนหมดเวลาทำงาน!")
    elif choice1 == "3":
        slow_print("\nหัวหน้ามองด้วยความตกใจและรีบเดินหนีไป เพราะคิดว่าคุณบ้า...")
    else:
        game_over("คุณยืนเอ๋อนานเกินไป หัวหน้าเลยเดินมาจ่ายงานเพิ่ม!")

    # Choice 2
    print("\n----------------------------------------")
    slow_print("คุณมาถึงหน้าห้องเก็บของ แต่ประตูถูกล็อกด้วยรหัส!")
    slow_print("มีกระดาษโพสต์อิทติดไว้ว่า: 'รหัสคือผลรวมของ 2 + 2 x 2'")
    
    code = input("\nกรอกรหัสผ่าน 4 หลัก/ตัวเลข: ")
    if code == "6":
        slow_print("\nเสียงกริ๊ก! ประตูเปิดออก... คุณเข้าใจลำดับการคำนวณทางคณิตศาสตร์ สมเป็น Dev!")
    else:
        game_over("รหัสผิด! ไซเรนเตือนภัยดังขึ้น รปภ. ลากคุณออกจากตึก!")

    # Choice 3
    print("\n----------------------------------------")
    slow_print("ในห้องเก็บของ... คุณเห็นคีย์บอร์ดวางอยู่บนแท่น แต่มันมี 'แมวออฟฟิศ' นอนทับอยู่!")
    slow_print("1: เอาขนมแมวเลียออกมาล่อ")
    slow_print("2: พยายามดึงคีย์บอร์ดออกมารวดเดียวแบบอินเดียนา โจนส์")
    slow_print("3: นั่งเกาหูให้แมวเพลินๆ")

    choice3 = input("\nเลือกทางเลือก (1-3): ")

    if choice3 == "1":
        slow_print("\nแมวเดินมาลอกกินขนมอย่างฟิน... คุณหยิบคีย์บอร์ดไปได้อย่างปลอดภัย!")
        victory()
    elif choice3 == "2":
        # สุ่มดวง
        if random.choice([True, False]):
            slow_print("\nสำเร็จ! คุณดึงออกได้อย่างรวดเร็ว แมวยังคงหลับสนิท!")
            victory()
        else:
            game_over("แมวตื่น! มันข่วนหน้าคุณ แล้ววิ่งหนีไปพร้อมคีย์บอร์ด!")
    elif choice3 == "3":
        game_over("คุณเกาหูแมวจนเพลิน รู้ตัวอีกทีก็หลับไปพร้อมกับแมว จนสว่าง...")
    else:
        game_over("แมวรำคาญที่คุณลังเล มันเลยกระโดดตะปบหน้าคุณ!")

if __name__ == "__main__":
    start_game()
